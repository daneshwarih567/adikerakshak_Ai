
"""AdikeRakshak AI - Safe local Ollama integration."""

import json
import urllib.request

OLLAMA_URL = "http://localhost:11434/api/generate"
OLLAMA_MODEL = "llama3.2:1b"

SAFE_DOSE_EN = (
    "No exact chemical dose is provided. Confirm the pest or disease "
    "with a KVK/agriculture officer and check the approved product label "
    "before applying any chemical."
)

SAFE_DOSE_KN = (
    "ನಿಖರವಾದ ರಾಸಾಯನಿಕ ಪ್ರಮಾಣವನ್ನು ಇಲ್ಲಿ ನೀಡಲಾಗಿಲ್ಲ. ಯಾವುದೇ ರಾಸಾಯನಿಕ "
    "ಬಳಸುವ ಮೊದಲು KVK ಅಥವಾ ಕೃಷಿ ಅಧಿಕಾರಿಯಿಂದ ರೋಗ ಅಥವಾ ಕೀಟವನ್ನು ದೃಢಪಡಿಸಿ "
    "ಮತ್ತು ಅನುಮೋದಿತ ಉತ್ಪನ್ನದ ಲೇಬಲ್ ಪರಿಶೀಲಿಸಿ."
)

CLASS_NAMES = {
    "healthy_leaf": "Healthy Leaf",
    "healthy_nut": "Healthy Nut",
    "healthy_trunk": "Healthy Trunk",
    "mahali_koleroga": "Mahali / Koleroga",
    "stem_bleeding": "Stem Bleeding",
    "bud borer": "Bud Borer",
    "bud_borer": "Bud Borer",
    "healthy_foot": "Healthy Foot",
    "stem cracking": "Stem Cracking",
    "stem_cracking": "Stem Cracking",
    "yellow leaf disease": "Yellow Leaf Disease",
    "yellow_leaf_disease": "Yellow Leaf Disease",
}


def _ollama_request(prompt, json_mode=False, timeout=240):
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {"temperature": 0.2}
    }

    if json_mode:
        payload["format"] = "json"

    request = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST"
    )

    with urllib.request.urlopen(request, timeout=timeout) as response:
        result = json.loads(response.read().decode("utf-8"))

    return result.get("response", "").strip()


def get_farmer_advice(question, disease=None, language="English"):
    """Answer farmer questions using local Llama."""

    prompt = f"""
You are AdikeRakshak AI, an agricultural information assistant
for arecanut farmers in Karnataka.

Detected model class: {disease or "Not provided"}
Farmer question: {question}
Response language: {language}

Rules:
- Answer in simple farmer-friendly language.
- Bud Borer is an insect pest. Bud Rot is a different disease.
- Never confuse different diseases or pests.
- Never invent pesticide names, brands, doses or application rates.
- Do not claim that an AI prediction is a confirmed diagnosis.
- For chemical treatment, ask the farmer to consult a KVK/agriculture
  officer and check the approved product label.
- If unsure, clearly say so.
- Answer only in the requested language.

Answer:
"""

    try:
        answer = _ollama_request(prompt)
        return answer or "No response received from the local AI model."

    except Exception as error:
        return (
            "Local Llama connection error. Check that Ollama is running "
            f"and model {OLLAMA_MODEL} is available. Details: {error}"
        )


def get_treatment_advisory(disease, confidence, language="English"):
    """
    Safe treatment panel.

    Treatment-panel content is controlled by Python, not generated by Llama.
    This prevents the model from mixing disease names or inventing doses.
    """

    raw_name = str(disease).strip()
    key = raw_name.lower().replace("-", "_").strip()
    display_name = CLASS_NAMES.get(key, raw_name)

    confidence = float(confidence)
    is_kannada = str(language).lower() in ("kannada", "ಕನ್ನಡ")

    healthy_classes = {
        "healthy_leaf", "healthy_nut", "healthy_trunk", "healthy_foot"
    }

    if key in healthy_classes:
        if is_kannada:
            rx = (
                f"ಮಾದರಿಯ ಪ್ರಕಾರ ಫಲಿತಾಂಶ: {display_name}. "
                "ಈ ಫಲಿತಾಂಶವು ಆರೋಗ್ಯಕರ ಭಾಗವನ್ನು ಸೂಚಿಸುತ್ತದೆ. "
                "ಈ ಫಲಿತಾಂಶದ ಆಧಾರದ ಮೇಲೆ ರಾಸಾಯನಿಕ ಚಿಕಿತ್ಸೆ ಮಾಡಬೇಡಿ."
            )
            advisory = (
                "ತೋಟವನ್ನು ನಿಯಮಿತವಾಗಿ ಪರಿಶೀಲಿಸಿ. ಯಾವುದೇ ಅಸಾಮಾನ್ಯ ಲಕ್ಷಣಗಳು "
                "ಕಂಡುಬಂದರೆ ಕೃಷಿ ಅಧಿಕಾರಿ ಅಥವಾ KVK ಯಿಂದ ಪರಿಶೀಲನೆ ಮಾಡಿಸಿ."
            )
        else:
            rx = (
                f"The model prediction is {display_name}. "
                "This indicates a healthy category. Do not apply chemical "
                "treatment based on this prediction."
            )
            advisory = (
                "Continue routine plantation monitoring. If unusual symptoms "
                "appear, seek an inspection from a KVK or agriculture officer."
            )

    else:
        if is_kannada:
            rx = (
                f"ಮಾದರಿಯು {display_name} ಎಂದು ಊಹಿಸಿದೆ. ಇದು ಖಚಿತ ರೋಗನಿರ್ಣಯವಲ್ಲ. "
                "ಚಿಕಿತ್ಸೆ ಆರಂಭಿಸುವ ಮೊದಲು ಸ್ಥಳೀಯ ಕೃಷಿ ಅಧಿಕಾರಿ ಅಥವಾ KVK ಯಿಂದ "
                "ಪರಿಶೀಲನೆ ಮಾಡಿಸಿ."
            )
            advisory = (
                "ಪೀಡಿತ ಸಸ್ಯದ ಲಕ್ಷಣಗಳನ್ನು ಗಮನಿಸಿ ಮತ್ತು ಸ್ಪಷ್ಟವಾದ ಫೋಟೋಗಳನ್ನು "
                "ತೆಗೆದುಕೊಳ್ಳಿ. ರೋಗ ಅಥವಾ ಕೀಟವನ್ನು ದೃಢಪಡಿಸದೆ ಯಾವುದೇ ಕೀಟನಾಶಕ "
                "ಅಥವಾ ಶಿಲೀಂಧ್ರನಾಶಕವನ್ನು ಬಳಸಬೇಡಿ."
            )
        else:
            rx = (
                f"The model prediction is {display_name}. This is not a "
                "confirmed diagnosis. Have the affected palm or plant part "
                "inspected by a local KVK or agriculture officer before "
                "starting treatment."
            )
            advisory = (
                "Observe the affected plant carefully and take clear photos "
                "of the symptoms. Do not apply an insecticide or fungicide "
                "until the cause has been confirmed by a qualified expert."
            )

    if confidence < 70:
        if is_kannada:
            advisory += (
                " ಮಾದರಿಯ ವಿಶ್ವಾಸ ಮಟ್ಟ ಕಡಿಮೆಯಿದೆ. ತಜ್ಞರಿಂದ ಪರಿಶೀಲನೆ "
                "ಮಾಡಿಸುವುದು ಅಗತ್ಯ."
            )
        else:
            advisory += (
                " The model confidence is low. Expert confirmation is "
                "especially important before taking treatment action."
            )

    return {
        "rx": rx,
        "dose": SAFE_DOSE_KN if is_kannada else SAFE_DOSE_EN,
        "advisory": advisory
    }
